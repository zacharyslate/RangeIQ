"""Write web/app/sw.js: the phone app's offline service worker.

Same approach as the Marfa Lights app: the cache name carries a hash of every
precached file, so any change to the app produces a new cache and phones pick
up the update on their next visit.

Run after changing anything in web/app/:   python scripts/build_sw.py
"""

from __future__ import annotations

import hashlib
import json
import pathlib

APP = pathlib.Path(__file__).resolve().parents[1] / "web" / "app"
SKIP_SUFFIX = {".md", ".txt"}
ON_DEMAND = ("vendor/three/", "terrain3d.js")   # 3D view: fetched the first time it's opened, then kept


def on_demand_files() -> list[str]:
    return [p.relative_to(APP).as_posix() for p in sorted(APP.rglob("*"))
            if p.is_file() and p.relative_to(APP).as_posix().startswith(ON_DEMAND) and p.suffix not in SKIP_SUFFIX]


def version_hash() -> str:
    """Hash of every app file, precached or on-demand, so any change ships to phones."""
    digest = hashlib.sha256()
    for rel in files() + on_demand_files():
        digest.update(rel.encode())
        digest.update((APP / rel).read_bytes())
    return digest.hexdigest()[:10]


def files() -> list[str]:
    out = []
    for path in sorted(APP.rglob("*")):
        if not path.is_file() or path.name == "sw.js" or path.suffix in SKIP_SUFFIX or path.name == "LICENSE":
            continue
        rel = path.relative_to(APP).as_posix()
        if rel.startswith(ON_DEMAND):
            continue
        out.append(rel)
    return out


def main() -> None:
    precache = files()
    version = version_hash()
    js = f"""/* Generated by scripts/build_sw.py. Do not edit by hand. */
const VERSION = "rangeiq-{version}";
const PRECACHE = {json.dumps(["./"] + precache, indent=0)};
const TILES = "rangeiq-tiles";
const LAZY = VERSION + "-lazy";        // 3D library: fetched on first use, replaced with each release
const TERRAIN = "rangeiq-terrain";     // last 3D terrain data, for opening 3D with no signal
const TILE_MAX = 600;

self.addEventListener("install", e => {{
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(PRECACHE.map(u => new Request(u, {{cache: "reload"}})))).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => ![VERSION, LAZY, TILES, TERRAIN].includes(k)).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

async function trim(cache, max) {{
  const keys = await cache.keys();
  for (let i = 0; i < keys.length - max; i++) await cache.delete(keys[i]);
}}

self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // 3D terrain data: network first, saved copy when there's no signal.
  if (url.origin === location.origin && url.pathname.includes("/api/terrain/")) {{
    e.respondWith(fetch(req).then(r => {{ if (r.ok) {{ const copy = r.clone(); caches.open(TERRAIN).then(c => c.put(req, copy)); }} return r; }})
      .catch(() => caches.match(req)));
    return;
  }}
  // Other ranch data and logs: always the network; the app keeps its own saved copy for offline use.
  if (url.origin === location.origin && url.pathname.includes("/api/")) return;
  if (url.origin === location.origin) {{
    // App files: precached ones from the cache; on-demand ones (3D library) cached the first time they load.
    e.respondWith(caches.match(req, {{ignoreSearch: true}}).then(hit => hit || fetch(req).then(r => {{
        if (r.ok && /vendor\\/three\\/|terrain3d\\.js/.test(url.pathname)) {{ const copy = r.clone(); caches.open(LAZY).then(c => c.put(req, copy)); }}
        return r;
      }}).catch(() => req.mode === "navigate" ? caches.match("./") : Response.error())));
    return;
  }}
  if (/nationalmap\\.gov$/.test(url.hostname)) {{
    // USGS imagery tiles (public domain): serve the saved copy, refresh in the background, keep the newest {600}.
    e.respondWith(caches.open(TILES).then(async c => {{
      const hit = await c.match(req);
      const net = fetch(req).then(r => {{ if (r.ok || r.type === "opaque") {{ c.put(req, r.clone()); trim(c, TILE_MAX); }} return r; }}).catch(() => hit);
      return hit || net;
    }}));
  }}
}});
"""
    (APP / "sw.js").write_text(js, encoding="utf-8")
    size_kb = sum((APP / rel).stat().st_size for rel in precache) / 1024
    print(f"sw.js: {len(precache)} files, {size_kb:.0f} KB precached, version {version}")


if __name__ == "__main__":
    main()
