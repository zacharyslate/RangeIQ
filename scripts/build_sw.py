"""Write web/app/sw.js: the phone app's offline service worker.

Same approach as the Marfa Lights app: the cache name carries a hash of every
precached file, so any change to the app produces a new cache and phones pick
up the update on their next visit.

Run after changing anything in web/app/:   python scripts/build_sw.py
"""

from __future__ import annotations

import hashlib
import json
import pathlib

APP = pathlib.Path(__file__).resolve().parents[1] / "web" / "app"
SKIP_SUFFIX = {".md", ".txt"}
ON_DEMAND = ("vendor/three/", "terrain3d.js")   # 3D view: fetched the first time it's opened, then kept


def on_demand_files() -> list[str]:
    return [p.relative_to(APP).as_posix() for p in sorted(APP.rglob("*"))
            if p.is_file() and p.relative_to(APP).as_posix().startswith(ON_DEMAND) and p.suffix not in SKIP_SUFFIX]


def version_hash() -> str:
    """Hash of every app file, precached or on-demand, so any change ships to phones."""
    digest = hashlib.sha256()
    for rel in files() + on_demand_files():
        digest.update(rel.encode())
        digest.update((APP / rel).read_bytes())
    return digest.hexdigest()[:10]


def files() -> list[str]:
    out = []
    for path in sorted(APP.rglob("*")):
        if not path.is_file() or path.name == "sw.js" or path.suffix in SKIP_SUFFIX or path.name == "LICENSE":
            continue
        rel = path.relative_to(APP).as_posix()
        if rel.startswith(ON_DEMAND):
            continue
        out.append(rel)
    return out


def main() -> None:
    precache = files()
    version = version_hash()
    js = f"""/* Generated by scripts/build_sw.py. Do not edit by hand. */
const VERSION = "rangeiq-{version}";
const PRECACHE = {json.dumps(["./"] + precache, indent=0)};
const TILES = "rangeiq-tiles";
const LAZY = VERSION + "-lazy";        // 3D library: fetched on first use, replaced with each release
const TERRAIN = "rangeiq-terrain";     // last 3D terrain data, for opening 3D with no signal
const TILE_MAX = 600;
const PHOTOS = "rangeiq-photos";       // crew photos seen on this phone, for looking at them with no signal
const PHOTO_MAX = 400;

self.addEventListener("install", e => {{
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(PRECACHE.map(u => new Request(u, {{cache: "reload"}})))).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => ![VERSION, LAZY, TILES, TERRAIN, PHOTOS].includes(k)).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

async function trim(cache, max) {{
  const keys = await cache.keys();
  for (let i = 0; i < keys.length - max; i++) await cache.delete(keys[i]);
}}

self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // 3D terrain data: network first, saved copy when there's no signal.
  // (The API may be on another site than the app, e.g. app on GitHub Pages, API on rangeiq.org.)
  if (url.pathname.includes("/api/terrain/")) {{
    e.respondWith(fetch(req).then(r => {{ if (r.ok) {{ const copy = r.clone(); caches.open(TERRAIN).then(c => c.put(req, copy).then(() => trim(c, 8))); }} return r; }})
      .catch(() => caches.match(req)));
    return;
  }}
  // Ranch photos: signed links change, so keep them by photo and size, not by the full link.
  if (url.pathname.includes("/api/photo-file/")) {{
    const key = new Request(url.origin + url.pathname + "?kind=" + (url.searchParams.get("kind") || "image"));
    e.respondWith(caches.open(PHOTOS).then(async c => {{
      const hit = await c.match(key);
      if (hit) return hit;
      const r = await fetch(req);
      if (r.ok || r.type === "opaque") {{ c.put(key, r.clone()); trim(c, PHOTO_MAX); }}
      return r;
    }}).catch(() => Response.error()));
    return;
  }}
  // Other ranch data and logs: always the network; the app keeps its own saved copy for offline use.
  if (url.pathname.includes("/api/")) return;
  if (url.origin === location.origin) {{
    // The 3D view's own code changes with the app, so get it fresh when there's signal (saved copy when there isn't);
    // a stale copy next to a new app.js breaks the 3D view.
    if (/terrain3d\\.js$/.test(url.pathname)) {{
      e.respondWith(fetch(req, {{cache: "no-cache"}}).then(r => {{
          if (r.ok) {{ const copy = r.clone(); caches.open(LAZY).then(c => c.put(req, copy)); }}
          return r;
        }}).catch(() => caches.open(LAZY).then(c => c.match(req, {{ignoreSearch: true}})).then(hit => hit || Response.error())));
      return;
    }}
    // App files: precached ones from this release's cache; the 3D library (three.js) cached the first time it loads.
    e.respondWith(caches.open(VERSION).then(c => c.match(req, {{ignoreSearch: true}})).then(hit => hit
      || caches.open(LAZY).then(c => c.match(req, {{ignoreSearch: true}}))).then(hit => hit || fetch(req).then(r => {{
        if (r.ok && /vendor\\/three\\//.test(url.pathname)) {{ const copy = r.clone(); caches.open(LAZY).then(c => c.put(req, copy)); }}
        return r;
      }})).catch(() => req.mode === "navigate" ? caches.match("./") : Response.error()));
    return;
  }}
  if (/nationalmap\\.gov$/.test(url.hostname)) {{
    // USGS imagery tiles (public domain): serve the saved copy, refresh in the background, keep the newest {600}.
    e.respondWith(caches.open(TILES).then(async c => {{
      const hit = await c.match(req);
      const net = fetch(req).then(r => {{ if (r.ok || r.type === "opaque") {{ c.put(req, r.clone()); trim(c, TILE_MAX); }} return r; }}).catch(() => hit);
      return hit || net;
    }}));
  }}
}});

// Where the API is: config.js sets it for the app (window.RANGEIQ_API); let it set it here too.
self.window = self;
try {{ importScripts("config.js"); }} catch (err) {{}}
const API_BASE = new URL(self.RANGEIQ_API || "../api/", self.location.href).href;

// ---- messenger notifications (Web Push). The server encrypts each message for this phone; show it, and open the
// conversation when it's tapped. Open copies of the app are told to fetch new messages at once.
self.addEventListener("push", e => {{
  let d = {{}};
  try {{ d = e.data ? e.data.json() : {{}}; }} catch (err) {{ d = {{body: e.data ? e.data.text() : ""}}; }}
  e.waitUntil((async () => {{
    // Tell the sender's phone it arrived (second tick). The receipt is signed by the server for this person.
    if (d.receipt) fetch(new URL("messages/delivered", API_BASE).href, {{method: "POST", headers: {{"Content-Type": "application/json"}},
      body: JSON.stringify({{receipt: d.receipt}})}}).catch(() => {{}});
    const wins = await self.clients.matchAll({{type: "window", includeUncontrolled: true}});
    wins.forEach(w => w.postMessage({{type: "chat-poll"}}));
    // If the app is open on that conversation, the message shows there; no need to buzz.
    if (wins.some(w => w.focused && w.visibilityState === "visible" && d.thread && (w.url || "").endsWith("#chat-" + encodeURIComponent(d.thread)))) return;
    await self.registration.showNotification(d.title || "RangeIQ", {{body: d.body || "", tag: d.tag || "rangeiq", renotify: true,
      // icon: the full-colour logo shown in the notification. badge: the small status-bar icon; Android draws only its
      // shape (a full square logo came out as a plain white square), so it's the longhorn silhouette on transparent.
      icon: "icon-192.png", badge: "badge-96.png", data: {{url: d.url || "./#chat", thread: d.thread || null}}}});
  }})());
}});
self.addEventListener("notificationclick", e => {{
  e.notification.close();
  const d = e.notification.data || {{}}, hash = d.thread ? "#chat-" + encodeURIComponent(d.thread) : "#chat";
  e.waitUntil(self.clients.matchAll({{type: "window", includeUncontrolled: true}}).then(wins => {{
    const w = wins.find(x => (x.url || "").includes("/app/"));
    if (w) {{ w.postMessage({{type: "open-chat", thread: d.thread}}); return w.focus(); }}
    return self.clients.openWindow(new URL("./" + hash, self.registration.scope).href);
  }}));
}});
"""
    (APP / "sw.js").write_text(js, encoding="utf-8")
    size_kb = sum((APP / rel).stat().st_size for rel in precache) / 1024
    print(f"sw.js: {len(precache)} files, {size_kb:.0f} KB precached, version {version}")


if __name__ == "__main__":
    main()
